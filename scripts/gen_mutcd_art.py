"""Writes site/js/mutcd-art.js: outlines of the MUTCD Interstate (M1-1) and U.S. route (M1-4) shields and the FHWA Series B, C and D digits and letters.

The artwork is read (as text, nothing is executed) from the npm package mutcd-ts (MIT, Copyright (c) 2026 Bryce Dorn), which reproduces the FHWA Standard
Highway Signs and Standard Alphabets, works of the U.S. government.
usage:  npm pack mutcd-ts && tar xzf mutcd-ts-*.tgz && python3 -I scripts/gen_mutcd_art.py package/dist/index.js site/js/mutcd-art.js
"""
import json
import re
import sys

src, out = sys.argv[1:3]
text = open(src, encoding="utf8").read()


def block(start: int, open_ch="{", close_ch="}") -> str:
    """The balanced {...} (string-aware) beginning at the first open_ch at or after start."""
    i = text.index(open_ch, start)
    depth, j, ins = 0, i, False
    while True:
        c = text[j]
        if ins:
            if c == "\\":
                j += 1
            elif c == '"':
                ins = False
        elif c == '"':
            ins = True
        elif c == open_ch:
            depth += 1
        elif c == close_ch:
            depth -= 1
            if depth == 0:
                return re.sub(r"\\x([0-9A-Fa-f]{2})", r"\\u00\1", text[i:j + 1])      # JS \xHH escapes become JSON ones
        j += 1


def glyphs(var: str, key="glyphs") -> dict:
    a = text.index(f"var {var} = ")
    return json.loads(block(text.index(f"{key}:", a)))


def art(var: str) -> list:
    a = text.index(f"var {var} = ")
    return [(p["d"], p["fill"]) for p in json.loads(block(a))["paths"]]


def r(d: str, n: int) -> str:
    return re.sub(r"-?\d+\.\d+", lambda m: f"{float(m.group()):.{n}f}".rstrip("0").rstrip("."), d)


CHARS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
B, C, D = glyphs("seriesB"), glyphs("seriesC"), glyphs("seriesD")
o = text.index("var official2024 = ")
D2 = {**D, **json.loads(block(o))}          # the 2024 Series D digits replace the older ones
pick = lambda g: {c: [g[c]["a"], r(g[c]["d"], 3)] for c in CHARS if c in g}
data = {"interstate": [[r(d, 2), f] for d, f in art("ART_M1_1")], "us": [[r(d, 2), f] for d, f in art("ART_M1_4")],
        "font": {"D": pick(D2), "C": pick(C), "B": pick(B)}}
open(out, "w", encoding="utf8").write(
    "// Generated by scripts/gen_mutcd_art.py: do not edit.\n"
    "// Outlines of the MUTCD Interstate (M1-1) and U.S. route (M1-4) shields in a 24 x 24 box, and FHWA Series D, C and B glyphs ([advance, path]) in units of the cap height.\n"
    "// Source: mutcd-ts (MIT, Copyright (c) 2026 Bryce Dorn), which reproduces the FHWA Standard Highway Signs and Standard Alphabets, works of the U.S. government.\n"
    f"export const ART = {json.dumps(data, separators=(',', ':'))};\n")
print({k: len(v) for k, v in data["font"].items()}, len(data["interstate"]), len(data["us"]))
